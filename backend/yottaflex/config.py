@dataclass(frozen=True)
class SplitBoundary:
    name: str
    start: date
    end_exclusive: date

    def contains(self, value: date) -> bool:
        return self.start <= value < self.end_exclusive


#: Chronological holdout boundaries. Rules are developed on `train`; validation
#: and test periods are evaluated later without re-tuning. Boundaries are fixed
#: event-time boundaries, not row percentages.
SPLITS: tuple[SplitBoundary, ...] = (
    SplitBoundary("train", date(2025, 9, 1), date(2026, 6, 1)),
    SplitBoundary("validation", date(2026, 6, 1), date(2026, 7, 15)),
    SplitBoundary("test", date(2026, 7, 15), date(2026, 10, 1)),
)


def split_for_date(value: date) -> str:
    for split in SPLITS:
        if split.contains(value):
            return split.name
    if value < SPLITS[0].start:
        return "train"
    return "test"


def split_for_timestamp(value: datetime) -> str:
    return split_for_date(value.date())


@dataclass(frozen=True)
class RunConfig:
    profile: str
    seed: int = DEFAULT_SEED
    lookback_days: int = 90
    reporting_currency: str = REPORTING_CURRENCY

    @property
    def spec(self) -> ProfileSpec:
        try:
            return PROFILES[self.profile]
        except KeyError as exc:  # pragma: no cover - guarded by CLI/API
            supported = ", ".join(sorted(PROFILES))
            raise ValueError(f"Unknown profile '{self.profile}'. Supported: {supported}") from exc

    @property
    def run_id(self) -> str:
        return run_key(self.profile, self.seed)

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["profile_spec"] = self.spec.to_dict()
        data["dataset_start"] = DATASET_START.isoformat()
        data["dataset_end"] = DATASET_END.isoformat()
        data["splits"] = [
            {"name": s.name, "start": s.start.isoformat(), "end_exclusive": s.end_exclusive.isoformat()}
            for s in SPLITS
        ]
        data["models"] = list(MODELS)
        data["generator_version"] = GENERATOR_VERSION
        data["attribution_rule_version"] = ATTRIBUTION_RULE_VERSION
        return data


def run_key(profile: str, seed: int) -> str:
    return f"{profile}-{seed}"


def utc_midnight(day: date) -> datetime:
    return datetime.combine(day, time.min)


def utc_end_of_day(day: date) -> datetime:
    return datetime.combine(day, time(23, 59, 59))


def date_range(start: date, end_inclusive: date) -> list[date]:
    days: list[date] = []
    cursor = start
    while cursor <= end_inclusive:
        days.append(cursor)
        cursor += timedelta(days=1)
    return days


def money(value: Decimal | str | int | float) -> Decimal:
    """Quantize to the reporting currency's 2-decimal precision.

    Authoritative financial values are stored as decimal strings. Binary floats
    are only used for random draws and are converted immediately.
    """

    return Decimal(str(value)).quantize(Decimal("0.01"))


@dataclass(frozen=True)
class Settings:
    data_root: Path = field(default_factory=lambda: PROJECT_ROOT / "data")
    ground_truth_root: Path = field(default_factory=lambda: PROJECT_ROOT / "ground_truth")
    reports_root: Path = field(default_factory=lambda: PROJECT_ROOT / "reports")

    @property
    def generated_root(self) -> Path:
        return self.data_root / "generated"

    @property
    def manifests_root(self) -> Path:
        return self.data_root / "manifests"

    @classmethod
    def from_env(cls) -> Settings:
        return cls(
            data_root=Path(os.environ.get("YOTTAFLEX_DATA_ROOT", PROJECT_ROOT / "data")),
            ground_truth_root=Path(
                os.environ.get("YOTTAFLEX_GROUND_TRUTH_ROOT", PROJECT_ROOT / "ground_truth")
            ),
            reports_root=Path(os.environ.get("YOTTAFLEX_REPORTS_ROOT", PROJECT_ROOT / "reports")),
        )

    def run_dir(self, run_id: str) -> Path:
        return self.generated_root / run_id

    def manifest_path(self, run_id: str) -> Path:
        return self.manifests_root / f"{run_id}.json"

    def active_run_path(self) -> Path:
        return self.manifests_root / "active_run.json"

    def run_index_path(self) -> Path:
        return self.manifests_root / "index.json"

    def ground_truth_dir(self, run_id: str) -> Path:
        return self.ground_truth_root / run_id
