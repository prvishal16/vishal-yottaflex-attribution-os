"""Analyst-facing report exports.

Every export is generated from the same filtered read model used by the
console, contains the complete matching record set (not only the visible
page), and carries the active run context so a downloaded file can always be
traced back to the dataset that produced it.

The module is deliberately report-agnostic: callers describe one or more
`Sheet`s plus a PDF projection, and this module owns serialization, metadata,
numeric/date fidelity and filename safety.
"""

from __future__ import annotations

import csv
import io
import json
import re
from dataclasses import dataclass, field
from datetime import UTC, date, datetime
from decimal import Decimal
from typing import Any, Literal

from yottaflex.api.deps import money, number

ExportFormat = Literal["csv", "json", "xlsx", "pdf", "sql", "zip"]

EXPORT_FORMATS = ("csv", "json", "xlsx", "pdf")
RUN_EXPORT_FORMATS = ("json", "csv", "xlsx", "pdf", "sql", "zip")

FORMAT_CONTENT_TYPES = {
    "csv": "text/csv; charset=utf-8",
    "json": "application/json; charset=utf-8",
    "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "pdf": "application/pdf",
    "sql": "application/zip",
    "zip": "application/zip",
}

FORMAT_LABELS = {
    "csv": "CSV",
    "json": "JSON",
    "xlsx": "XLSX",
    "pdf": "PDF",
    "sql": "SQL package",
    "zip": "ZIP bundle",
}

FORMAT_DESCRIPTIONS = {
    "csv": "Flat table of every matching record.",
    "json": "Structured records plus run, model and filter context.",
    "xlsx": "Multi-sheet analyst workbook with a summary sheet.",
    "pdf": "Printable summary with scope, reconciliation and page numbers.",
    "sql": "Portable schema.sql, load.sql and CSV data generated by DuckDB.",
    "zip": "Manifest, configuration, counts, validation and evaluation artifacts.",
}

#: Columns that must stay numeric in XLSX and numeric in JSON payloads.
NUMERIC_COLUMNS = {
    "budget_amount",
    "spend",
    "attributed_revenue",
    "conversions",
    "unique_converting_contacts",
    "touchpoints_credited",
    "roi_pct",
    "roas",
    "cost_per_conversion",
    "average_order_value",
    "issue_count",
}

#: Columns that must stay dates in XLSX and ISO strings in JSON/CSV.
DATE_COLUMNS = {"start_at", "end_at"}

NULL_TOKEN = ""

_SAFE_STEM = re.compile(r"[^A-Za-z0-9._-]+")


@dataclass(frozen=True)
class Sheet:
    name: str
    columns: list[str]
    records: list[dict[str, Any]]
    numeric: frozenset[str] = field(default_factory=frozenset)
    dates: frozenset[str] = field(default_factory=frozenset)


@dataclass(frozen=True)
class PdfColumn:
    key: str
    header: str
    weight: float
    align: str = "L"
    kind: str = "text"


@dataclass(frozen=True)
class PdfSpec:
    columns: list[PdfColumn]
    table_heading: str = "Records"
    summary_heading: str = "Reconciliation summary"
    max_rows: int = 200
    empty_message: str = "No records match the active filters."


def _normalise(value: Any) -> Any:
    if value is None:
        return None
    if isinstance(value, Decimal):
        return float(value)
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, date):
        return value.isoformat()
    return value


def _date_value(value: Any) -> Any:
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value
    if isinstance(value, date):
        return datetime.combine(value, datetime.min.time())
    text = str(value)
    cleaned = text.replace("Z", "")
    for pattern in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M:%S", "%Y-%m-%d"):
        try:
            return datetime.strptime(cleaned, pattern)
        except ValueError:
            continue
    return text


def _safe_stem(stem: str) -> str:
    cleaned = _SAFE_STEM.sub("-", stem).strip(".-")
    return cleaned or "yottaflex-export"


def build_context(
    *,
    run_id: str,
    profile: str | None,
    seed: int | None,
    model: str | None,
    sort: str | None = None,
    order: str | None = None,
    filters: dict[str, Any] | None = None,
    row_count: int,
    scope: str = "All records matching the active filters",
    generated_at: str | None = None,
    report: str = "Campaign performance",
    stem: str | None = None,
    currency: str = "EUR",
    artifact_type: str = "analytical_export",
    contains_ground_truth: bool = False,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    context: dict[str, Any] = {
        "run_id": run_id,
        "dataset": run_id,
        "profile": profile,
        "seed": seed,
        "model": model,
        "report": report,
        "scope": scope,
        "filters": {
            key: value
            for key, value in (filters or {}).items()
            if value not in (None, "")
        },
        "row_count": row_count,
        "generated_at": generated_at or datetime.now(UTC).isoformat().replace("+00:00", "Z"),
        "currency": currency,
        "artifact_type": artifact_type,
        "contains_ground_truth": contains_ground_truth,
        "row_semantics": "Every matching record is included; the visible page is not a limit.",
        "stem": _safe_stem(stem or "campaign-performance"),
    }
    if sort is not None:
        context["sort"] = sort
    if order is not None:
        context["order"] = order
    for key, value in (extra or {}).items():
        context[key] = value
    return context


def _csv_bytes(sheet: Sheet) -> bytes:
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(sheet.columns)
    for record in sheet.records:
        writer.writerow(
            [
                NULL_TOKEN if record.get(column) is None else record.get(column)
                for column in sheet.columns
            ]
        )
    return buffer.getvalue().encode("utf-8")


def _json_rows(sheet: Sheet) -> list[dict[str, Any]]:
    return [
        {column: _normalise(record.get(column)) for column in sheet.columns}
        for record in sheet.records
    ]


def _json_bytes(
    context: dict[str, Any], sheets: list[Sheet], primary: dict[str, Any] | None = None
) -> bytes:
    payload: dict[str, Any] = {
        "context": context,
        "columns": sheets[0].columns,
        "rows": _json_rows(sheets[0]),
        "sheets": [
            {
                "name": sheet.name,
                "columns": sheet.columns,
                "row_count": len(sheet.records),
                "rows": _json_rows(sheet),
            }
            for sheet in sheets
        ],
    }
    for key, value in (primary or {}).items():
        payload[key] = value
    return (json.dumps(payload, indent=2, default=str) + "\n").encode("utf-8")


def _xlsx_value(value: Any, numeric: bool, is_date: bool) -> Any:
    if value is None or value == "":
        return None
    if numeric:
        return number(value)
    if is_date:
        return _date_value(value)
    if isinstance(value, Decimal):
        return float(value)
    if isinstance(value, (dict, list)):
        return json.dumps(value, default=str)
    return value


def _xlsx_bytes(
    context: dict[str, Any],
    sheets: list[Sheet],
    summary_rows: list[tuple[str, Any]],
) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    workbook = Workbook()
    header_fill = PatternFill("solid", fgColor="1F2933")
    header_font = Font(color="D8FF3E", bold=True)
    label_font = Font(color="9AA6B2", bold=False)

    summary = workbook.active
    summary.title = "Summary"
    summary["A1"] = context["report"]
    summary["A1"].font = Font(size=14, bold=True, color="D8FF3E")
    summary.append([])
    for label, value in summary_rows:
        if isinstance(value, (dict, list)):
            value = json.dumps(value, default=str)
        summary.append([label, value])
        summary.cell(row=summary.max_row, column=1).font = label_font
    summary.append([])
    summary.append(["Report context"])
    summary.cell(row=summary.max_row, column=1).font = Font(bold=True)
    for key, value in context.items():
        if isinstance(value, dict):
            value = ", ".join(f"{k}={v}" for k, v in value.items())
        elif isinstance(value, list):
            value = ", ".join(str(item) for item in value)
        summary.append([key, value])
        summary.cell(row=summary.max_row, column=1).font = label_font
    summary.column_dimensions["A"].width = 30
    summary.column_dimensions["B"].width = 84
    for row in summary.iter_rows(min_row=2, max_col=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)

    def write_sheet(sheet: Sheet) -> None:
        worksheet = workbook.create_sheet(sheet.name[:31])
        worksheet.append(sheet.columns)
        for cell in worksheet[1]:
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(vertical="center")
        for record in sheet.records:
            worksheet.append(
                [
                    _xlsx_value(
                        record.get(column),
                        column in sheet.numeric,
                        column in sheet.dates,
                    )
                    for column in sheet.columns
                ]
            )
        worksheet.freeze_panes = "A2"
        if worksheet.max_row > 1:
            worksheet.auto_filter.ref = (
                f"A1:{get_column_letter(len(sheet.columns))}{worksheet.max_row}"
            )
        for index, column in enumerate(sheet.columns, start=1):
            width = max(len(str(column)) + 2, 12)
            if column in {"campaign_name", "campaign_id", "primary_channel_name", "explanation"}:
                width = 38
            worksheet.column_dimensions[get_column_letter(index)].width = min(width, 60)
        for row in worksheet.iter_rows(min_row=2):
            for cell in row:
                if isinstance(cell.value, datetime):
                    cell.number_format = "yyyy-mm-dd hh:mm"
                elif isinstance(cell.value, float):
                    cell.number_format = "#,##0.00"
                elif isinstance(cell.value, int):
                    cell.number_format = "#,##0"

    for sheet in sheets:
        write_sheet(sheet)

    buffer = io.BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()


def _pdf_text(value: Any) -> str:
    text = "" if value is None else str(value)
    return text.encode("latin-1", "replace").decode("latin-1")


def _pdf_format(value: Any, kind: str) -> str:
    if value is None or value == "":
        return "n/a"
    if kind == "money":
        return f"EUR {number(value) or 0:,.2f}"
    if kind == "number":
        return f"{number(value) or 0:,.2f}"
    return _pdf_text(value)


def _pdf_bytes(
    context: dict[str, Any],
    sheets: list[Sheet],
    summary_rows: list[tuple[str, Any]],
    pdf_spec: PdfSpec,
) -> bytes:
    from fpdf import FPDF

    class Report(FPDF):
        def footer(self) -> None:
            self.set_y(-12)
            self.set_font("Helvetica", size=8)
            self.set_text_color(120, 130, 140)
            self.cell(0, 8, f"Page {self.page_no()}", align="C")

    pdf = Report(orientation="landscape", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=14)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(20, 30, 40)
    pdf.cell(0, 10, _pdf_text(context["report"]), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(90, 100, 110)
    scope = (
        f"Dataset {context['run_id']}  |  Profile {context.get('profile') or 'n/a'}  |  "
        f"Model {context.get('model') or 'n/a'}  |  {context['row_count']} rows  |  "
        f"Generated {context['generated_at']}"
    )
    pdf.cell(0, 6, _pdf_text(scope), new_x="LMARGIN", new_y="NEXT")
    filters = ", ".join(f"{key}={value}" for key, value in context["filters"].items()) or "none"
    pdf.cell(0, 6, _pdf_text(f"Filters: {filters}"), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, _pdf_text(f"Scope: {context['scope']}"), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, _pdf_text(f"Currency: {context['currency']}"), new_x="LMARGIN", new_y="NEXT")
    if context.get("contains_ground_truth"):
        pdf.ln(2)
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(180, 40, 40)
        pdf.cell(
            0,
            6,
            _pdf_text(
                "EVALUATION ARTIFACT - contains synthetic ground-truth labels. "
                "Not model input and not a production accuracy claim."
            ),
            new_x="LMARGIN",
            new_y="NEXT",
        )
        pdf.set_text_color(90, 100, 110)
    pdf.ln(2)

    if summary_rows:
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(20, 30, 40)
        pdf.cell(0, 7, _pdf_text(pdf_spec.summary_heading), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", size=9)
        pdf.set_text_color(60, 70, 80)
        for label, value in summary_rows:
            if isinstance(value, (dict, list)):
                value = json.dumps(value, default=str)
            text = _pdf_text(value)
            pdf.set_x(pdf.l_margin)
            if len(text) > 80:
                pdf.multi_cell(0, 6, f"{_pdf_text(label)}: {text}")
            else:
                pdf.cell(78, 6, _pdf_text(label))
                pdf.cell(0, 6, text, new_x="LMARGIN", new_y="NEXT")

    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(20, 30, 40)
    pdf.cell(0, 7, _pdf_text(pdf_spec.table_heading), new_x="LMARGIN", new_y="NEXT")

    primary = sheets[0]
    available = pdf.w - pdf.l_margin - pdf.r_margin
    total_weight = sum(column.weight for column in pdf_spec.columns) or 1
    widths = [available * column.weight / total_weight for column in pdf_spec.columns]

    pdf.set_font("Helvetica", "B", 8)
    pdf.set_text_color(30, 40, 50)
    for column, width in zip(pdf_spec.columns, widths, strict=True):
        pdf.cell(width, 7, _pdf_text(column.header), border=1, align="C")
    pdf.ln()
    pdf.set_font("Helvetica", size=8)

    def fit(text: str, width: float) -> str:
        if pdf.get_string_width(text) <= width:
            return text
        ellipsis = "..."
        while text and pdf.get_string_width(text + ellipsis) > width:
            text = text[:-1]
        return text + ellipsis

    if not primary.records:
        pdf.set_font("Helvetica", "I", 9)
        pdf.cell(0, 7, _pdf_text(pdf_spec.empty_message), new_x="LMARGIN", new_y="NEXT")
    for record in primary.records[: pdf_spec.max_rows]:
        for column, width in zip(pdf_spec.columns, widths, strict=True):
            value = _pdf_format(record.get(column.key), column.kind)
            pdf.cell(width, 6, fit(value, width - 1), border=1, align=column.align)
        pdf.ln()
    if len(primary.records) > pdf_spec.max_rows:
        pdf.ln(2)
        pdf.set_font("Helvetica", "I", 8)
        pdf.cell(
            0,
            6,
            _pdf_text(
                f"Showing the first {pdf_spec.max_rows} of {len(primary.records)} matching rows. "
                "Use CSV or XLSX for the complete set."
            ),
            new_x="LMARGIN",
            new_y="NEXT",
        )
    return bytes(pdf.output())


def build_export(
    export_format: str,
    *,
    context: dict[str, Any],
    columns: list[str],
    records: list[dict[str, Any]],
    extras: dict[str, tuple[list[str], list[dict[str, Any]]]] | None = None,
    summary_rows: list[tuple[str, Any]] | None = None,
    pdf_spec: PdfSpec | None = None,
) -> tuple[bytes, str, str]:
    """Return (payload, content type, filename) for the requested format.

    Retained as a convenience wrapper for the campaign-performance report so
    existing callers and tests keep the same contract.
    """

    sheets = [
        Sheet(
            name="Campaigns",
            columns=columns,
            records=records,
            numeric=frozenset(NUMERIC_COLUMNS),
            dates=frozenset(DATE_COLUMNS),
        )
    ]
    for title, (header, rows) in (extras or {}).items():
        numeric = frozenset(NUMERIC_COLUMNS)
        sheets.append(Sheet(name=title, columns=header, records=rows, numeric=numeric))
    if pdf_spec is None:
        pdf_spec = DEFAULT_CAMPAIGN_PDF
    return build_report_export(
        export_format,
        context=context,
        sheets=sheets,
        summary_rows=summary_rows or [],
        pdf_spec=pdf_spec,
    )


def build_report_export(
    export_format: str,
    *,
    context: dict[str, Any],
    sheets: list[Sheet],
    summary_rows: list[tuple[str, Any]] | None = None,
    pdf_spec: PdfSpec | None = None,
    json_primary: dict[str, Any] | None = None,
) -> tuple[bytes, str, str]:
    if export_format not in EXPORT_FORMATS:
        raise ValueError(f"Unsupported export format: {export_format}")
    if not sheets:
        raise ValueError("A report export needs at least one sheet.")
    summary_rows = summary_rows or []
    stem = _safe_stem(str(context.get("stem") or "yottaflex-export"))
    if export_format == "csv":
        payload = _csv_bytes(sheets[0])
        extension = "csv"
    elif export_format == "json":
        payload = _json_bytes(context, sheets, json_primary)
        extension = "json"
    elif export_format == "xlsx":
        payload = _xlsx_bytes(context, sheets, summary_rows)
        extension = "xlsx"
    else:
        payload = _pdf_bytes(
            context, sheets, summary_rows, pdf_spec or DEFAULT_CAMPAIGN_PDF
        )
        extension = "pdf"
    return payload, FORMAT_CONTENT_TYPES[export_format], f"{stem}.{extension}"


