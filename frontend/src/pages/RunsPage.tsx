import {
  CheckCircle2,
  Database,
  Fingerprint,
  History,
  LoaderCircle,
  Play,
  RefreshCw,
  ShieldCheck,
  Sparkles,
  TriangleAlert,
} from "lucide-react";
import { useState, type FormEvent } from "react";
import { Link } from "react-router-dom";

import { api, type RunExportFileFormat } from "../api/client";
import { ValidationBadge } from "../components/Badges";
import { ExportMenu, type ExportOption } from "../components/ExportMenu";
import {
  Badge,
  Button,
  CopyButton,
  ErrorState,
  LoadingState,
  PageHeader,
  SectionCard,
} from "../components/Primitives";
import { useAsync } from "../hooks/useAsync";
import { useRunContext } from "../hooks/useRunContext";
import type { RunManifest, VerifyJob } from "../types/api";
import {
  formatCurrency,
  formatDate,
  formatDateTime,
  formatNumber,
  truncateHash,
} from "../utils/format";

const PROFILES = [
  { value: "small", label: "Small", detail: "30 cmp · 500 contacts · 200 opps" },
  { value: "demo", label: "Demo", detail: "100 cmp · 8k contacts · 2k opps" },
  { value: "full", label: "Full", detail: "500 cmp · 50k contacts · 10k opps" },
];

const MANIFEST_VOLUME = [
  { key: "campaigns", label: "Campaigns" },
  { key: "contacts", label: "Contacts" },
  { key: "touchpoints", label: "Touchpoints" },
  { key: "opportunities", label: "Opportunities" },
  { key: "sessions", label: "Sessions" },
  { key: "orders", label: "Orders" },
  { key: "cost_records", label: "Cost records" },
  { key: "attribution_results", label: "Attribution results" },
  { key: "exceptions", label: "Exceptions" },
];

const RUN_FORMAT_META: Array<{
  format: RunExportFileFormat;
  label: string;
  description: string;
}> = [
  {
    format: "json",
    label: "JSON manifest",
    description: "Manifest, config, counts and aggregate metrics with run context.",
  },
  {
    format: "csv",
    label: "CSV entity counts",
    description: "Every manifest entity and its row count.",
  },
  {
    format: "xlsx",
    label: "XLSX run workbook",
    description: "Summary, counts, generation, attribution, validation and evaluation.",
  },
  {
    format: "pdf",
    label: "PDF run summary",
    description: "Printable run status and entity counts.",
  },
  {
    format: "sql",
    label: "SQL package (ZIP)",
    description: "schema.sql, load.sql and every base table as CSV, generated by DuckDB.",
  },
  {
    format: "zip",
    label: "Artifact bundle (ZIP)",
    description: "Manifest, config, counts, validation and aggregate metrics. No labels.",
  },
];

function runExportOptions(runId: string): ExportOption[] {
  return RUN_FORMAT_META.map((meta) => ({
    ...meta,
    href: api.runExportUrl(runId, meta.format),
  }));
}

export function RunsPage() {
  const {
    runs,
    activeRunId,
    effectiveRunId,
    loading: runsLoading,
    selectRun,
    refreshRuns,
  } = useRunContext();
  const [profile, setProfile] = useState("small");
  const [seed, setSeed] = useState("20261022");
  const [strict, setStrict] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [actionError, setActionError] = useState<string | null>(null);
  const [actionSuccess, setActionSuccess] = useState<string | null>(null);
  const [validating, setValidating] = useState(false);
  const [manifestOverride, setManifestOverride] = useState<RunManifest | null>(null);
  const [verifyProfile, setVerifyProfile] = useState("small");
  const [verifySeed, setVerifySeed] = useState("20261022");
  const [verifyJob, setVerifyJob] = useState<VerifyJob | null>(null);

  const excludedColumns = verifyJob?.result?.excluded_nondeterministic_columns ?? {};
  const excludedColumnCount = Object.values(excludedColumns).reduce(
    (total, columns) => total + (columns?.length ?? 0),
    0,
  );
  const excludedColumnList = Object.entries(excludedColumns)
    .map(([table, columns]) => `${table}: ${columns.join(", ")}`)
    .join("; ");

  async function runVerification() {
    setActionError(null);
    setActionSuccess(null);
    try {
      const started = await api.startVerify(verifyProfile, Number(verifySeed));
      setVerifyJob(started);
      const finished = await pollVerification(started.job_id);
      setVerifyJob(finished);
      setActionSuccess(
        finished.status === "REPRODUCIBLE"
          ? `Reproducibility confirmed for ${verifyProfile} seed ${verifySeed}: both generations produced identical canonical hashes.`
          : `Verification finished with status ${finished.status}.`,
      );
    } catch (reason) {
      setActionError(
        reason instanceof Error ? reason.message : "Verification could not be started.",
      );
    }
  }

  async function pollVerification(jobId: string): Promise<VerifyJob> {
    for (let attempt = 0; attempt < 400; attempt += 1) {
      const job = await api.verifyJob(jobId);
      if (job.status !== "RUNNING") return job;
      setVerifyJob(job);
      await new Promise((resolve) => window.setTimeout(resolve, 1500));
    }
    throw new Error("Verification is still running. Refresh the page to check again.");
  }

  const manifestState = useAsync(
    () => api.run(effectiveRunId ?? ""),
    [effectiveRunId],
    { enabled: Boolean(effectiveRunId) },
  );
  const manifest =
    manifestOverride?.run_id === effectiveRunId ? manifestOverride : manifestState.data;

  async function generateDataset(event: FormEvent) {
    event.preventDefault();
    setGenerating(true);
    setActionError(null);
    setActionSuccess(null);
    try {
      const numericSeed = Number(seed);
      const generated = await api.generate(profile, numericSeed, strict);
      await refreshRuns();
      selectRun(generated.run_id);
      setManifestOverride(generated);
      setActionSuccess(
        `Generated ${generated.run_id}: ${formatNumber(generated.counts.touchpoints)} touchpoints, ${formatNumber(generated.counts.orders)} orders, ${formatNumber(generated.counts.exceptions)} fixtures.`,
      );
    } catch (reason) {
      setActionError(reason instanceof Error ? reason.message : "Dataset generation failed.");
    } finally {
      setGenerating(false);
    }
  }

  async function rerunValidation() {
    if (!effectiveRunId) return;
    setValidating(true);
    setActionError(null);
    setActionSuccess(null);
    try {
      await api.validate(effectiveRunId);
      await refreshRuns();
      manifestState.reload();
      setManifestOverride(null);
      setActionSuccess(`Validation re-ran for ${effectiveRunId}.`);
    } catch (reason) {
      setActionError(reason instanceof Error ? reason.message : "Validation failed.");
    } finally {
      setValidating(false);
    }
  }

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="Runs & reproducibility"
        title="Same seed. Same numbers. Every time."
        description="Generate datasets, inspect manifest hashes, and re-run the validation contract. Reproducibility is proven by canonical table hashes, not vibes."
        meta={
          <>
            <Badge tone="accent" dot>Deterministic generator</Badge>
            <span>Canonical CSV hashing</span>
            <span>Ground truth stored separately</span>
          </>
        }
        actions={
          <Button
            variant="secondary"
            size="md"
            icon={RefreshCw}
            onClick={() => void refreshRuns()}
            disabled={runsLoading}
          >
            Refresh registry
          </Button>
        }
      />

      {actionError ? (
        <div className="inline-alert inline-alert--danger">
          <TriangleAlert size={17} />
          <div>
            <strong>Operation failed</strong>
            <span>{actionError}</span>
          </div>
        </div>
      ) : null}
      {actionSuccess ? (
        <div className="inline-alert inline-alert--success">
          <CheckCircle2 size={17} />
          <div>
            <strong>Completed</strong>
            <span>{actionSuccess}</span>
          </div>
        </div>
      ) : null}

      <div className="runs-top-grid">
        <SectionCard
          title="Generate a dataset"
          description="Core data is drawn from a seeded RNG, fixtures are injected deliberately, then every downstream stage runs in order."
          className="generate-panel"
        >
          <form className="generate-form" onSubmit={(event) => void generateDataset(event)}>
            <div className="profile-picker">
              {PROFILES.map((option) => (
                <button
                  type="button"
                  key={option.value}
                  className={`profile-option ${profile === option.value ? "is-active" : ""}`}
                  onClick={() => setProfile(option.value)}
                >
                  <span>{option.label}</span>
                  <small>{option.detail}</small>
                  <i aria-hidden="true" />
                </button>
              ))}
            </div>

            <div className="form-row">
              <label className="field">
                <span>Seed</span>
                <input
                  value={seed}
                  onChange={(event) => setSeed(event.target.value.replace(/[^0-9]/g, ""))}
                  inputMode="numeric"
                  pattern="[0-9]*"
                  min={0}
                  max={2147483647}
                  required
                />
              </label>
              <label className="checkbox-field">
                <input
                  type="checkbox"
                  checked={strict}
                  onChange={(event) => setStrict(event.target.checked)}
                />
                <span>
                  Strict validation
                  <small>Abort generation if any validation check fails.</small>
                </span>
              </label>
            </div>

            <div className="generate-form__footer">
              <div>
                <span className="generate-form__hint">
                  {profile === "full"
                    ? "Full profile may take several minutes."
                    : profile === "demo"
                      ? "Demo profile usually completes in under a minute."
                      : "Small profile is built for rapid review and tests."}
                </span>
              </div>
              <Button
                type="submit"
                variant="primary"
                size="md"
                icon={generating ? LoaderCircle : Play}
                disabled={generating || !seed}
                className={generating ? "is-loading" : ""}
              >
                {generating ? "Generating…" : "Generate dataset"}
              </Button>
            </div>
          </form>

          <div className="pipeline-strip" aria-label="Pipeline order">
            {["Core CSV", "DuckDB views", "Attribution", "Detection", "Analytics", "Validation", "Evaluation", "Manifest"].map(
              (stage, index) => (
                <span key={stage}>
                  <i>{String(index + 1).padStart(2, "0")}</i>
                  {stage}
                </span>
              ),
            )}
          </div>
        </SectionCard>

        <SectionCard
          title="Selected manifest"
          description={
            manifest
              ? `${manifest.run_id} · generated ${formatDateTime(manifest.generated_at)}`
              : "No manifest loaded."
          }
          className="manifest-panel"
          actions={
            manifest ? (
              <div className="manifest-actions">
                <ValidationBadge status={manifest.validation?.overall_status} />
                <ExportMenu
                  buttonLabel="Export run"
                  size="sm"
                  variant="ghost"
                  options={runExportOptions(manifest.run_id)}
                  note="No ground truth"
                />
              </div>
            ) : undefined
          }
        >
          {manifestState.error && !manifest ? (
            <ErrorState
              compact
              message={manifestState.error.message}
              onRetry={manifestState.reload}
            />
          ) : manifestState.loading && !manifest ? (
            <LoadingState rows={5} />
          ) : manifest ? (
            <>
              <div className="manifest-status">
                <div>
                  <span className="eyebrow">Run status</span>
                  <strong>{manifest.status}</strong>
                  <span>{manifest.profile} profile · seed {manifest.seed}</span>
                </div>
                <Badge tone={manifest.run_id === activeRunId ? "accent" : "neutral"} dot>
                  {manifest.run_id === activeRunId ? "Active" : "History"}
                </Badge>
              </div>

              <div className="hash-panel">
                <div className="hash-panel__label">
                  <Fingerprint size={14} />
                  <span>Combined canonical hash</span>
                </div>
                <code>{manifest.combined_hash}</code>
                <CopyButton value={manifest.combined_hash} label="Copy hash" />
              </div>

              <div className="manifest-kpis">
                {MANIFEST_VOLUME.map((field) => (
                  <div key={field.key}>
                    <span>{field.label}</span>
                    <strong>{formatNumber(manifest.counts[field.key])}</strong>
                  </div>
                ))}
              </div>

              <div className="manifest-assurance">
                <div>
                  <span>Attributed revenue</span>
                  <strong>{formatCurrency(manifest.attribution.attributed_revenue)}</strong>
                </div>
                <div>
                  <span>Validation</span>
                  <strong>
                    {manifest.validation?.totals.warnings ?? 0} warnings ·{" "}
                    {manifest.validation?.totals.failures ?? 0} failures
                  </strong>
                </div>
                <div>
                  <span>Detection F1</span>
                  <strong>
                    {manifest.evaluation?.totals.f1_pct ?? "—"}% on{" "}
                    {manifest.evaluation?.totals.ground_truth ?? 0} labels
                  </strong>
                </div>
              </div>

              <div className="manifest-footer">
                <span>
                  {manifest.validation?.totals.checks ?? 0} validation checks ·{" "}
                  {manifest.attribution.conversions} eligible conversions
                </span>
                <Button
                  variant="secondary"
                  size="sm"
                  icon={ShieldCheck}
                  onClick={() => void rerunValidation()}
                  disabled={validating}
                >
                  {validating ? "Re-running…" : "Re-run validation"}
                </Button>
              </div>
              <p className="manifest-repro">
                Reproduce this run with{" "}
                <code>
                  yottaflex verify --profile {manifest.profile} --seed {manifest.seed}
                </code>
                . Generation is deterministic; verification compares canonical table hashes.
              </p>
            </>
          ) : (
            <EmptyManifest />
          )}
        </SectionCard>
      </div>

      <SectionCard
        title="Run registry"
        description="Every generated profile and seed is addressable. Selecting a run rewires the console without mutating it."
        actions={<Badge tone="neutral">{runs.length} runs</Badge>}
        flush
      >
        {runsLoading && !runs.length ? (
          <div className="panel-pad"><LoadingState rows={5} /></div>
        ) : runs.length === 0 ? (
          <EmptyManifest />
        ) : (
          <div className="table-wrap">
            <table className="data-table data-table--runs">
              <thead>
                <tr>
                  <th>Run</th>
                  <th>Profile</th>
                  <th>Seed</th>
                  <th>Generated</th>
                  <th>Campaigns</th>
                  <th>Contacts</th>
                  <th>Touchpoints</th>
                  <th>Opportunities</th>
                  <th>Exceptions</th>
                  <th>Status</th>
                  <th>Hash</th>
                  <th aria-label="Select" />
                </tr>
              </thead>
              <tbody>
                {runs.map((run) => (
                  <tr
                    key={run.run_id}
                    className={run.run_id === effectiveRunId ? "is-selected" : undefined}
                  >
                    <td>
                      <div className="run-cell">
                        <Database size={14} />
                        <div>
                          <strong>{run.run_id}</strong>
                          {run.run_id === activeRunId ? <Badge tone="accent">active</Badge> : null}
                        </div>
                      </div>
                    </td>
                    <td><Badge tone="neutral">{run.profile}</Badge></td>
                    <td className="mono">{run.seed}</td>
                    <td>{formatDate(run.generated_at)}</td>
                    <td className="is-numeric">
                      {formatNumber(run.counts?.campaigns ?? run.campaigns)}
                    </td>
                    <td className="is-numeric">
                      {formatNumber(run.counts?.contacts ?? run.contacts)}
                    </td>
                    <td className="is-numeric">
                      {formatNumber(run.counts?.touchpoints ?? run.touchpoints)}
                    </td>
                    <td className="is-numeric">
                      {formatNumber(run.counts?.opportunities ?? run.opportunities)}
                    </td>
                    <td className="is-numeric">
                      {formatNumber(run.counts?.exceptions ?? run.issues)}
                    </td>
                    <td>
                      <Badge tone={run.status === "COMPLETE" ? "positive" : "warning"} dot>
                        {run.status.toLowerCase()}
                      </Badge>
                    </td>
                    <td>
                      <code className="hash-short" title={run.combined_hash}>
                        {truncateHash(run.combined_hash, 10)}
                      </code>
                    </td>
                    <td>
                      <Button
                        variant={run.run_id === effectiveRunId ? "ghost" : "secondary"}
                        size="sm"
                        onClick={() => {
                          selectRun(run.run_id === activeRunId ? null : run.run_id);
                          setManifestOverride(null);
                        }}
                        disabled={run.run_id === effectiveRunId}
                      >
                        {run.run_id === effectiveRunId ? "Selected" : "Open"}
                      </Button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </SectionCard>

      <SectionCard
        title="Prove reproducibility"
        description="Regenerate the profile twice in an isolated directory and compare canonical table hashes. The active dataset is never modified."
        actions={
          verifyJob ? (
            <Badge
              tone={
                verifyJob.status === "REPRODUCIBLE"
                  ? "positive"
                  : verifyJob.status === "RUNNING"
                    ? "info"
                    : "warning"
              }
              dot
            >
              {verifyJob.status === "RUNNING" ? "Verifying" : verifyJob.status.replaceAll("_", " ")}
            </Badge>
          ) : undefined
        }
        className="verify-panel"
      >
        <div className="verify-panel__row">
          <label className="field field--inline">
            <span>Profile</span>
            <select
              value={verifyProfile}
              onChange={(event) => setVerifyProfile(event.target.value)}
              disabled={verifyJob?.status === "RUNNING"}
            >
              {PROFILES.map((option) => (
                <option key={option.value} value={option.value}>
                  {option.label}
                </option>
              ))}
            </select>
          </label>
          <label className="field field--inline">
            <span>Seed</span>
            <input
              value={verifySeed}
              onChange={(event) => setVerifySeed(event.target.value.replace(/[^0-9]/g, ""))}
              inputMode="numeric"
              disabled={verifyJob?.status === "RUNNING"}
            />
          </label>
          <Button
            variant="secondary"
            size="md"
            icon={ShieldCheck}
            onClick={() => void runVerification()}
            disabled={verifyJob?.status === "RUNNING" || !verifySeed}
          >
            {verifyJob?.status === "RUNNING" ? "Verifying…" : "Run verification"}
          </Button>
        </div>

        {verifyJob?.status === "RUNNING" ? (
          <p className="verify-panel__running">
            Two isolated generations are being produced. This can take a few minutes for the larger
            profiles; the active run stays untouched.
          </p>
        ) : verifyJob?.status === "FAILED" ? (
          <div className="inline-alert inline-alert--danger">
            <TriangleAlert size={17} />
            <div>
              <strong>Verification failed to run</strong>
              <span>{verifyJob.error}</span>
            </div>
          </div>
        ) : verifyJob?.result ? (
          <div className="verify-result">
            <div className="verify-result__hashes">
              <div>
                <span>Left generation</span>
                <code title={verifyJob.result.left_combined_hash}>
                  {truncateHash(verifyJob.result.left_combined_hash, 22)}
                </code>
              </div>
              <div>
                <span>Right generation</span>
                <code title={verifyJob.result.right_combined_hash}>
                  {truncateHash(verifyJob.result.right_combined_hash, 22)}
                </code>
              </div>
            </div>
            <p>
              {verifyJob.result.reproducible
                ? `Both generations produced identical canonical hashes across every table. ${excludedColumnCount} timestamp column(s) are excluded from hashing by design${
                    excludedColumnList ? ` (${excludedColumnList})` : ""
                  }.`
                : `${verifyJob.result.differences.length} table(s) differ between the two generations.`}
            </p>
            {verifyJob.result.differences.length ? (
              <div className="table-wrap">
                <table className="data-table">
                  <thead>
                    <tr>
                      <th>Table</th>
                      <th>Left rows</th>
                      <th>Right rows</th>
                      <th>Left hash</th>
                      <th>Right hash</th>
                    </tr>
                  </thead>
                  <tbody>
                    {verifyJob.result.differences.map((difference) => (
                      <tr key={difference.table}>
                        <td>{difference.table}</td>
                        <td className="is-numeric">{formatNumber(difference.left_rows)}</td>
                        <td className="is-numeric">{formatNumber(difference.right_rows)}</td>
                        <td><code className="hash-short">{truncateHash(difference.left_sha256, 12)}</code></td>
                        <td><code className="hash-short">{truncateHash(difference.right_sha256, 12)}</code></td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            ) : null}
          </div>
        ) : (
          <p className="verify-panel__running">
            No verification has been run in this session yet. The small profile finishes fastest.
          </p>
        )}
      </SectionCard>

      <div className="repro-grid">
        <ReproCard
          icon={History}
          title="Canonical, not incidental"
          body="Hashes exclude computed timestamps and ingestion clocks. Business records are sorted by primary keys, so the same seed produces byte-identical canonical tables."
        />
        <ReproCard
          icon={ShieldCheck}
          title="Labels stay outside"
          body="Ground truth is written to a sibling directory after the dataset. Detection reads only persisted records; the evaluator is the sole consumer of labels."
        />
        <ReproCard
          icon={Sparkles}
          title="Rerun and compare"
          body="`yottaflex verify --profile small` regenerates the same run and compares combined hashes, proving reproducibility on demand."
        />
      </div>

      <div className="table-note">
        <Database size={13} />
        <span>
          Selected run is stored locally in this browser. Use the dataset selector in the top bar to
          move between runs. <Link to="/data-quality">Review trust status</Link>.
        </span>
      </div>
    </div>
  );
}

function ReproCard({
  icon: Icon,
  title,
  body,
}: {
  icon: typeof Fingerprint;
  title: string;
  body: string;
}) {
  return (
    <article className="repro-card">
      <span className="repro-card__icon"><Icon size={17} /></span>
      <div>
        <strong>{title}</strong>
        <p>{body}</p>
      </div>
    </article>
  );
}

function EmptyManifest() {
  return (
    <div className="empty-state">
      <Database size={22} />
      <h3>No dataset selected</h3>
      <p>Generate a small profile or select an existing run from the registry.</p>
    </div>
  );
}
